// Writes lib/assistant-tabs.mjs: every workspace sidebar tab with its address, read from the
// workspace components. The help assistant uses it to link an answer to the exact tab.
// Run again after adding, renaming or removing a sidebar tab:  node scripts/gen-assistant-tabs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import routes from '../lib/workspace-routes.js';

// base -> component file. `skip` = keys that are not addressable tabs (a nested sub-sidebar's own
// entries); `last` = when a key is declared twice, keep the later label (PrWorkspace lists the
// Installation variant first).
const FILES = {
  '/sales': { file: 'SalesWorkspace' }, '/procurement': { file: 'ProcurementWorkspace' }, '/stores': { file: 'StoresWorkspace' },
  '/pr': { file: 'PrWorkspace', last: true }, '/production/shop': { file: 'WorkersPanel', skip: ['overview', 'roster'] },
  '/planning': { file: 'PlanningWorkspace' }, '/qc': { file: 'QcWorkspace' }, '/dispatch': { file: 'DispatchWorkspace' },
  '/installation': { file: 'InstallationWorkspace' }, '/service-expenses': { file: 'ServiceExpenses' }, '/hr': { file: 'HrWorkspace' },
  '/accounts': { file: 'AccountsWorkspace' }, '/engineering': { file: 'EngineeringWorkspace' }, '/approvals': { file: 'ApprovalsWorkspace' },
};
const out = {};
for (const [base, { file, skip = [], last }] of Object.entries(FILES)) {
  const src = readFileSync(new URL(`../components/${file}.jsx`, import.meta.url), 'utf8');
  // A sidebar entry is written { key: '…', label: '…', icon: … }. Form fields have no icon; a
  // parent that only groups other entries (group: true) is not a tab itself. [^{}]* stops at the
  // parent's own braces, so a group's first child is not swallowed with it.
  const tabs = new Map();
  for (const m of src.matchAll(/\{\s*key: '([\w-]+)',\s*label: '([^']+)',\s*icon: \w+([^{}]*)/g)) {
    if (/group:\s*true/.test(m[3]) || skip.includes(m[1]) || (tabs.has(m[1]) && !last)) continue;
    tabs.set(m[1], m[2]);
  }
  out[base] = [...tabs].map(([key, label]) => ({ label, href: `${base}/${routes.tabSlug(key)}` }));
}
writeFileSync(new URL('../lib/assistant-tabs.mjs', import.meta.url),
  `// Generated by scripts/gen-assistant-tabs.mjs. Do not edit by hand.\nexport const TABS = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.entries(out).map(([b, t]) => `${b}: ${t.length}`).join(', '));
