// Writes lib/assistant-tabs.mjs: every workspace sidebar tab with its address, read from the
// workspace components. The help assistant uses it to link an answer to the exact tab.
// Run again after adding, renaming or removing a sidebar tab:  node scripts/gen-assistant-tabs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import routes from '../lib/workspace-routes.js';

const FILES = { '/sales': 'SalesWorkspace', '/procurement': 'ProcurementWorkspace', '/stores': 'StoresWorkspace', '/pr': 'PrWorkspace', '/production/shop': 'WorkersPanel', '/planning': 'PlanningWorkspace', '/qc': 'QcWorkspace', '/dispatch': 'DispatchWorkspace', '/installation': 'InstallationWorkspace', '/hr': 'HrWorkspace', '/accounts': 'AccountsWorkspace', '/engineering': 'EngineeringWorkspace', '/approvals': 'ApprovalsWorkspace' };
const out = {};
for (const [base, file] of Object.entries(FILES)) {
  const src = readFileSync(new URL(`../components/${file}.jsx`, import.meta.url), 'utf8');
  // A sidebar entry is written { key: '…', label: '…', icon: … }. Form fields have no icon; a
  // parent that only groups other entries (group: true) is not a tab itself.
  const seen = new Set();
  out[base] = [...src.matchAll(/\{\s*key: '([\w-]+)',\s*label: '([^']+)',\s*icon: \w+([^}]*)\}/g)]
    .filter(m => !/group:\s*true/.test(m[3]) && !seen.has(m[1]) && seen.add(m[1]))
    .map(m => ({ label: m[2], href: `${base}/${routes.tabSlug(m[1])}` }));
}
writeFileSync(new URL('../lib/assistant-tabs.mjs', import.meta.url),
  `// Generated by scripts/gen-assistant-tabs.mjs. Do not edit by hand.\nexport const TABS = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.entries(out).map(([b, t]) => `${b}: ${t.length}`).join(', '));
