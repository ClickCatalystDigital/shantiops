// Writes server/api-routes.generated.js: one lazy import per route file under server/api/. Runs before
// every build and dev start (package.json prebuild/predev); the output is committed too, so a build
// that skips npm scripts still works. Fails if a route exists both here and in app/api/ (Next would
// serve the app/api one and the server/api one would silently never run).
import { readdirSync, statSync, existsSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { buildTree } from '../lib/api-match.mjs';

const SRC = 'server/api';
const OUT = 'server/api-routes.generated.js';

function* walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (name === 'route.js') yield p;
  }
}

const keys = existsSync(SRC) ? [...walk(SRC)].map((f) => relative(SRC, f).replace(/\/?route\.js$/, '')) : [];
for (const k of keys) {
  if (!k) throw new Error('gen-api-routes: server/api/route.js (the bare /api path) is not supported');
  if (existsSync(join('app/api', k, 'route.js'))) throw new Error(`gen-api-routes: /api/${k} exists in both app/api and server/api`);
}
buildTree(keys); // throws on clashing [param] names or duplicates

const out = `// Generated by scripts/gen-api-routes.mjs from server/api/. Do not edit.
export const ROUTES = {
${keys.map((k) => `  ${JSON.stringify(k)}: () => import(${JSON.stringify(`./api/${k}/route.js`)}),`).join('\n')}
};
`;
if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== out) writeFileSync(OUT, out);
console.log(`gen-api-routes: ${keys.length} routes`);
