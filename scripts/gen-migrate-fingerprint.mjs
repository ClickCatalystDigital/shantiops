// Writes lib/migrate-fingerprint.generated.js: a hash of lib/db.js and every local file it imports
// (followed transitively), i.e. all code migrate() can run. initDB() skips migrate() when the
// database already carries this fingerprint (app_settings 'schema_fingerprint'), so a production
// start costs one query instead of hundreds of schema statements. Runs before every build (package.json).
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { dirname, join, resolve, relative } from 'node:path';
import { createHash } from 'node:crypto';

const ENTRY = 'lib/db.js';
const OUT = 'lib/migrate-fingerprint.generated.js';
const EXT = ['', '.js', '.mjs', '/index.js'];

function resolveImport(spec, fromFile) {
  let base;
  if (spec.startsWith('@/')) base = resolve(spec.slice(2));
  else if (spec.startsWith('.')) base = resolve(dirname(fromFile), spec);
  else return null; // package: its version is fixed by package-lock, not part of migrate's own code
  for (const e of EXT) if (existsSync(base + e) && statSync(base + e).isFile()) return base + e;
  throw new Error(`gen-migrate-fingerprint: cannot resolve ${spec} from ${fromFile}`);
}

const seen = new Set();
function visit(file) {
  if (seen.has(file) || file === resolve(OUT)) return; // its own output is not code migrate() runs
  seen.add(file);
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(/^\s*(?:import|export)\b[^'"]*?from\s+['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/gm)) {
    const r = resolveImport(m[1] || m[2], file);
    if (r) visit(r);
  }
}
visit(resolve(ENTRY));

const files = [...seen].map((f) => relative(process.cwd(), f)).sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update('\0').update(readFileSync(f)).update('\0');
const fp = hash.digest('hex').slice(0, 24);

const out = `// Generated by scripts/gen-migrate-fingerprint.mjs. Do not edit.
// Covers: ${files.join(', ')}
export const MIGRATE_CODE_FINGERPRINT = ${JSON.stringify(fp)};
`;
if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== out) writeFileSync(OUT, out);
console.log(`gen-migrate-fingerprint: ${fp} (${files.length} files)`);
