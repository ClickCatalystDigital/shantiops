import assert from 'node:assert/strict';
import { orderAlertReason } from './order-alerts.mjs';
const t = '2026-10-10';
assert.equal(orderAlertReason({ track_status: 'WIP', expected_delivery_date: '2026-10-01' }, t), 'delivery_overdue');
assert.equal(orderAlertReason({ track_status: 'Pending', order_date: '2026-08-01' }, t), 'pending_long');
assert.equal(orderAlertReason({ track_status: 'Pending', order_date: '2026-10-01' }, t), null);
assert.equal(orderAlertReason({ track_status: 'Dispatched', expected_delivery_date: '2026-10-01' }, t), null);
assert.equal(orderAlertReason({ track_status: 'Ready', expected_delivery_date: '2026-10-01', packing_status: 'dispatched' }, t), null);
assert.equal(orderAlertReason({ status: 'cancelled', track_status: 'Pending', order_date: '2026-01-01' }, t), null);
console.log('order-alerts selfcheck ok');
