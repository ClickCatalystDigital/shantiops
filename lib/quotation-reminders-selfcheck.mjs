import assert from 'node:assert/strict';
import { quotationFollowupReason as r } from './quotation-reminders.mjs';
const T = '2026-09-25';
assert.equal(r({ status: 'draft', valid_until: '2026-09-26' }, T), null);
assert.equal(r({ status: 'accepted', valid_until: '2026-09-20' }, T), null);
assert.equal(r({ status: 'sent', valid_until: '2026-09-20', has_order: 1 }, T), null);
assert.equal(r({ status: 'sent', valid_until: '2026-09-24' }, T), 'expired');
assert.equal(r({ status: 'sent', valid_until: '2026-09-25' }, T), 'expiring');
assert.equal(r({ status: 'sent', valid_until: '2026-09-28' }, T), 'expiring');
assert.equal(r({ status: 'sent', valid_until: '2026-09-29', sent_at: '2026-09-24 10:00:00' }, T), null);
assert.equal(r({ status: 'sent', sent_at: '2026-09-18 09:00:00' }, T), 'stale');
assert.equal(r({ status: 'sent', sent_at: '2026-09-19 09:00:00' }, T), null);
assert.equal(r({ status: 'sent', sent_at: '2026-09-10', last_activity_at: '2026-09-15 12:00:00' }, T), null);
assert.equal(r({ status: 'sent', sent_at: '2026-09-10', last_activity_at: '2026-09-10 12:00:00' }, T), 'stale');
assert.equal(r({ status: 'sent', quotation_date: '2026-09-01' }, T), 'stale');
console.log('quotation-reminders selfcheck ok');
