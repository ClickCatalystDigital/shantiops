import assert from 'node:assert';
import { rootOf, defaultCompany, groupForms, boxGroups } from './packing-forms.mjs';
const by = new Map([[1, { id: 1, parent_id: null, name: 'BOILER' }], [2, { id: 2, parent_id: 1, name: 'Feed Line' }], [3, { id: 3, parent_id: 2, name: 'x' }]]);
assert.equal(rootOf(3, by).name, 'BOILER');
assert.equal(rootOf(99, by), null);
assert.equal(defaultCompany('MS Tapered Chimney', 'Shanti Techno Fab'), 'Shanti Techno Fab');
assert.equal(defaultCompany('x', null), 'Shanti Boilers');
assert.equal(defaultCompany('SDC', 'Shanti Boilers'), 'Shanti Boilers');
const f = groupForms([{ section: 'SDC' }, { section: 'BOILER' }, { section: 'SDC' }, { section: '' }], 'BOILER');
assert.deepEqual(f.map(x => [x.name, x.kind]), [['BOILER', 'master'], ['SDC', 'annexure'], ['Other', 'annexure']]);
const g = boxGroups([{ box_no: 'BOX 2', s_no: 1 }, { box_no: 'BOX 1', s_no: 2 }, { box_no: 'BOX 2', s_no: 3 }, { box_no: 'BOX 10', s_no: 4 }]);
assert.deepEqual(g.map(x => [x.box, x.items.length]), [['BOX 1', 1], ['BOX 2', 2], ['BOX 10', 1]]);
assert.deepEqual(boxGroups([{ box_no: 'BOX 1', s_no: 1 }, { box_no: 'LOOSE 2', s_no: 2 }, { box_no: 'MOUNTED', s_no: 3 }]).map(x => x.box), ['LOOSE 2', 'MOUNTED', 'BOX 1']);
console.log('packing-forms ok');
