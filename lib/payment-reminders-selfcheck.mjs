import assert from 'node:assert/strict';
import { needsPaymentReminder, weekKey } from './payment-reminders.mjs';
const t = '2026-09-29';
const o = { total: 100000, received: 0, order_date: '2026-07-01' };
assert.equal(needsPaymentReminder(o, t), true);
assert.equal(needsPaymentReminder({ ...o, order_date: '2026-09-20' }, t), false, 'too new');
assert.equal(needsPaymentReminder({ ...o, order_date: '2024-01-01' }, t), false, 'legacy');
assert.equal(needsPaymentReminder({ ...o, received: 100000 }, t), false, 'paid');
assert.equal(needsPaymentReminder({ ...o, received: 98000 }, t), false, 'TDS-sized shortfall');
assert.equal(needsPaymentReminder({ ...o, received: 40000 }, t), true, 'part paid');
assert.equal(needsPaymentReminder({ ...o, status: 'cancelled' }, t), false);
assert.equal(needsPaymentReminder({ ...o, track_status: 'Closed' }, t), false);
assert.equal(needsPaymentReminder({ ...o, total: 0 }, t), false);
assert.equal(weekKey('2026-09-29'), weekKey('2026-09-28'));
assert.notEqual(weekKey('2026-09-29'), weekKey('2026-10-06'));
console.log('payment-reminders selfcheck ok');
