import assert from 'node:assert/strict';
import { stockStage } from './stock-stage.mjs';
const k = f => stockStage(f)?.key;
assert.equal(stockStage({}), null);
assert.equal(k({ reserved: true }), 'reserved');
assert.equal(k({ reserved: true, routedTo: 'dispatch' }), 'routed_dispatch');
assert.equal(k({ routedTo: 'production', issued: true }), 'on_floor');
assert.equal(k({ issued: true, onPackingList: true }), 'on_packing_list');
assert.equal(k({ onPackingList: true, packed: true, dispatched: true }), 'dispatched');
assert.equal(k({ status: 'Received' }), 'in_stock');
console.log('stock-stage selfcheck: ok');
